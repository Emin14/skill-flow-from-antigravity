/**
 * Returns today's unique motivational message from the array of 240 items.
 * Advances automatically by 1 message each calendar day.
 */
export function getTodayMessage(): string {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = (dayOfYear - 1) % DAILY_MESSAGES.length;
  return DAILY_MESSAGES[Math.max(0, index)];
}
