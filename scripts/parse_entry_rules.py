def clean_hyphens_and_spaces(text):
    # Fix hyphenated line breaks e.g. "умерен- ные" -> "умеренные"
    # Also "раз- гружать" -> "разгружать"
    text = re.sub(r'([а-яёА-ЯЁa-zA-Z])-\s+([а-яёА-ЯЁa-zA-Z])', r'\1\2', text)
    # Fix space before punctuation
    text = re.sub(r'\s+([,;:?.!)])', r'\1', text)
    text = re.sub(r'([(])\s+', r'\1', text)
    # Multiple spaces
    text = re.sub(r'\s+', ' ', text).strip()
    return text

