# Regex to format registers properly
def format_registers_in_text(text):
    if not text: return ""
    for reg, formatted in REGISTER_MAP.items():
        # Match register at start of string or after space/paren/comma, not followed by dot or letter
        pattern = r'(?<![а-яёА-ЯЁa-zA-Z])' + re.escape(reg) + r'(?!\.)(?=\s+[а-яёА-ЯЁa-zA-Z\(])'
        text = re.sub(pattern, formatted, text)
    return text

