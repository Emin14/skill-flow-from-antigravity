def clean_ocr_hyphenated_words(text):
    if not text: return ""
    
    # 1. Clean 'ин- струмент' with space after hyphen
    text = re.sub(r'([а-яёА-ЯЁ])- ([а-яёА-ЯЁ])', r'\1\2', text)
    
    # 2. Apply special explicit fixes first
    for k, v in SPECIAL_OCR_FIXES.items():
        text = re.sub(r'\b' + re.escape(k) + r'\b', v, text)
        
    # 3. Process hyphenated Russian tokens
    def replace_hyphen(m):
        w = m.group(0)
        w_low = w.lower()
        
        if w_low in GENUINE_WORDS:
            return w
            
        if w_low in SPECIAL_OCR_FIXES:
            return SPECIAL_OCR_FIXES[w_low]
            
        # Check legitimate по-... adverbs (ending in -ому, -ему, -ски, -цки, -ьи)
        if w_low.startswith('по-'):
            rest = w_low[3:]
            if re.search(r'(ому|ему|ски|цки|ьи)$', rest):
                return w
            else:
                return w_low[:2] + rest
                
        if any(w_low.startswith(p) for p in GENUINE_PREFIXES):
            return w
            
        if any(w_low.endswith(s) for s in GENUINE_SUFFIXES):
            return w
            
        # Repeated words: e.g. давным-давно, день-деньской, точь-в-точь
        parts = w.split('-')
        if len(parts) == 2 and parts[0].lower() == parts[1].lower():
            if parts[0].lower() == 'пур':
                return 'пурпур'
            return w
            
        # Otherwise, this is an OCR line break hyphen! Merge it.
        return ''.join(parts)
        
    text = re.sub(r'\b([а-яёА-ЯЁ]{2,})-([а-яёА-ЯЁ]{2,})\b', replace_hyphen, text)
    return text

def sanitize_english_homoglyphs(text):
    """Replaces accidental Cyrillic characters in English text with Latin counterparts and fixes split ligatures."""
    if not text: return ""
    CYR_TO_LAT = {
        'а': 'a', 'А': 'A',
        'с': 'c', 'С': 'C',
        'е': 'e', 'Е': 'E',
        'о': 'o', 'О': 'O',
        'р': 'p', 'Р': 'P',
        'х': 'x', 'Х': 'X',
        'у': 'y', 'У': 'Y',
        'і': 'i', 'І': 'I',
        'ј': 'j', 'Ј': 'J',
        'ѕ': 's', 'Ѕ': 'S',
        'В': 'B', 'Н': 'H',
        'К': 'K', 'М': 'M', 'Т': 'T'
    }
    result = []
    for ch in text:
        if ch in CYR_TO_LAT:
            result.append(CYR_TO_LAT[ch])
        else:
            result.append(ch)
    t = ''.join(result)
    
    # Fix split OCR ligatures like 'traffi c', 'diffi cult', 'offi ce'
    t = re.sub(r'\b([a-zA-Z]*(?:ffi|ffl|fi|fl))\s+([a-zA-Z]+)\b', r'\1\2', t)
    return t
