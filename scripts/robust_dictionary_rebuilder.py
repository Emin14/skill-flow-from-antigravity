def clean_ocr_line(line):
    # Remove line breaks hyphens at end of words
    line = re.sub(r'(\w+)-\s*\n\s*(\w+)', r'\1\2', line)
    # Remove standalone page numbers or headers like "careen\n110\n"
    line = re.sub(r'\n[a-z-]+\n\d+\n', '\n', line)
    return line

def extract_registers(text):
    regs = []
    # Match register labels at beginning of defs or in text
    for abbrev, full in REGISTER_MAP.items():
        # Check if abbrev occurs as whole token (e.g. 'мор. ', 'воен. ', '(мор.)')
        pattern = r'(?:\b|\()' + re.escape(abbrev) + r'(?:\b|\))'
        if re.search(pattern, text):
            if full not in regs:
                regs.append(full)
            # Remove from text
            text = re.sub(pattern, '', text)
    # Clean extra spaces
    text = re.sub(r'\s+', ' ', text).strip(' ,;')
    return text, regs

