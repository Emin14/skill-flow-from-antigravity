def restore_hyphens(text):
    if not text:
        return text
    for pat, repl in HYPHEN_REPLACEMENTS:
        text = re.sub(pat, repl, text, flags=re.I)
    return text

count_text_fixed = 0

for item in oxford_data:
    for m in item.get('meanings', []):
        tr = m.get('translation', '')
        new_tr = restore_hyphens(tr)
        if new_tr != tr:
            m['translation'] = new_tr
            count_text_fixed += 1
            
        for ex in m.get('examples', []):
            ru = ex.get('ru', '')
            new_ru = restore_hyphens(ru)
            if new_ru != ru:
                ex['ru'] = new_ru
                count_text_fixed += 1
                
    for p in item.get('phrases', []):
        tr = p.get('translation', '')
        new_tr = restore_hyphens(tr)
        if new_tr != tr:
            p['translation'] = new_tr
            count_text_fixed += 1
            
        for ex in p.get('examples', []):
            ru = ex.get('ru', '')
            new_ru = restore_hyphens(ru)
            if new_ru != ru:
                ex['ru'] = new_ru
                count_text_fixed += 1

print(f"Fixed {count_text_fixed} text fields with restored hyphens!")

