unextracted = []

for item in data:
    w = item['word']
    for m in item.get('meanings', []):
        t = m.get('translation', '')
        
        # Check if t starts with one or multiple abbreviations
        # e.g., 'радио, тлв.', 'ав., авто', 'мор., воен.', 'ж.-д.', etc.
        for pat, reg_name in ABBREV_PATTERNS:
            if re.search(r'^\s*(?:\()?' + pat, t):
                unextracted.append((w, 'meaning', m['id'], t, m.get('register', [])))
                break

    for p in item.get('phrases', []):
        t = p.get('translation', '')
        for pat, reg_name in ABBREV_PATTERNS:
            if re.search(r'^\s*(?:\()?' + pat, t):
                unextracted.append((w, 'phrase', p['id'], t, p.get('register', [])))
                break

print(f"Found {len(unextracted)} unextracted register prefixes in dataset:\n")
for w, kind, id_, t, regs in unextracted:
    print(f"[{w}] ({kind} {id_}): '{t}' (current reg: {regs})")
