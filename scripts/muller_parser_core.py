def clean_hyphenation(text: str) -> str:
    """Fix soft hyphens and line-break hyphens."""
    text = unicodedata.normalize('NFKC', text)
    # Remove soft hyphens
    text = text.replace('\u00ad', '')
    text = text.replace('\xad', '')
    # Fix broken hyphenation at line breaks: e.g. "похище-\nние" or "похище- ние"
    text = re.sub(r'([А-Яа-яA-Za-z])-[\s\n]+([А-Яа-яA-Za-z])', r'\1\2', text)
    # Normalize spaces
    text = re.sub(r'[ \t\r\f\v]+', ' ', text)
    return text.strip()

