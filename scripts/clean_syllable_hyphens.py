def is_valid_hyphen_word(word_str):
    w_low = word_str.lower().strip()
    if w_low in VALID_FULL_WORDS:
        return True
    parts = w_low.split('-')
    if len(parts) != 2:
        return False
    p1, p2 = parts
    if p2 in VALID_HYPHEN_SUFFIXES or p2.startswith('л'):
        return True
    if p1 in VALID_HYPHEN_PREFIXES:
        return True
    if p1 in VALID_COMPOUND_ADJECTIVES and len(p2) >= 3:
        return True
    if p1.startswith('по-') or p1 == 'по' or p1 == 'из' or p1 == 'во':
        return True
    # Reduplications: e.g. синий-синий, мало-помалу
    if p1 == p2:
        return True
    return False

def clean_hyphens_in_text(text):
    if not text:
        return ''
    def replace_hyphen_match(m):
        full = m.group(0)
        p1 = m.group(1)
        p2 = m.group(2)
        if is_valid_hyphen_word(full):
            return full
        # Syllable break from PDF line break -> join
        return p1 + p2
        
    t = re.sub(r'([а-яА-Яa-zA-Z]+)-([а-яА-Яa-zA-Z]+)', replace_hyphen_match, text)
    return t

fixed_words = 0
for w in words:
    for m in w.get('meanings', []):
        old_tr = m.get('translation', '')
        new_tr = clean_hyphens_in_text(old_tr)
        if old_tr != new_tr:
            fixed_words += 1
            m['translation'] = new_tr
        for ex in m.get('examples', []):
            if ex.get('ru'):
                ex['ru'] = clean_hyphens_in_text(ex['ru'])

print(f"Fixed {fixed_words} translations by removing spurious syllable hyphens.")

