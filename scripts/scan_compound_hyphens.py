found_issues = []

def check_text(text, context):
    for pat, fix in COMPOUND_PATTERNS:
        if re.search(pat, text, re.I):
            found_issues.append((context, text, fix))

for item in oxford_data:
    w = item['word']
    for m in item.get('meanings', []):
        check_text(m.get('translation', ''), f"{w} [meaning {m['id']}]")
        for e_idx, ex in enumerate(m.get('examples', [])):
            check_text(ex.get('ru', ''), f"{w} [meaning {m['id']}, ex {e_idx}]")
            
    for p in item.get('phrases', []):
        check_text(p.get('translation', ''), f"{w} [phrase {p['id']}]")
        for e_idx, ex in enumerate(p.get('examples', [])):
            check_text(ex.get('ru', ''), f"{w} [phrase {p['id']}, ex {e_idx}]")

